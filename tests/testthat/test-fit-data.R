test_that("raw and frequency data compress observations without expansion", {
  d <- dl_fit_data(c(2, 1, 2, NA, 0))
  expect_s3_class(d, "dl_fit_data")
  expect_identical(d$type, "raw")
  expect_equal(d$x, c(0, 1, 2))
  expect_equal(d$counts, c(1, 1, 2))
  expect_equal(d$n, 4)
  expect_equal(d$removed, 1)
  expect_null(d$lower)
  f <- dl_fit_data(c(2, 1, 2, 9), c(1e9, 3, 2, 0))
  expect_equal(f$x, c(1, 2))
  expect_equal(f$counts, c(3, 1e9 + 2))
  expect_length(f$x, 2)
  expect_equal(dl_fit_describe(f)$mean, (3 + 2 * (1e9 + 2)) / (1e9 + 5))
})

test_that("data preparation rejects invalid observations and weights", {
  expect_error(dl_fit_data(numeric()), "nonempty")
  expect_error(dl_fit_data("1"), "numeric")
  expect_error(dl_fit_data(matrix(1:4, 2)), "numeric")
  expect_error(dl_fit_data(c(1, Inf)), "finite")
  expect_error(dl_fit_data(c(1, NA), na.rm = FALSE), "Missing")
  expect_error(dl_fit_data(c(NA_real_, NaN)), "No complete")
  expect_error(dl_fit_data(1, na.rm = 1), "TRUE or FALSE")
  for (w in list(-1, .5, Inf, 2^53)) expect_error(dl_fit_data(1, w), "Frequencies")
  expect_error(dl_fit_data(1, 0), "positive")
  expect_error(dl_fit_data(1:2, 1), "equal length")
  expect_equal(dl_fit_data(1:2, c(NA, 1))$removed, 1)
})

test_that("grouped classes retain interval likelihood information", {
  g <- dl_fit_data(lower = c(-Inf, 0, 1), upper = c(0, 1, Inf),
                   frequency = c(2, 3, 4))
  expect_identical(g$type, "grouped")
  expect_equal(g$x, c(NA_real_, .5, NA_real_))
  expect_equal(g$n, 9)
  desc <- dl_fit_describe(g)
  expect_true(desc$approximate)
  expect_true(is.na(desc$mean))
  expect_true(is.na(desc$integer))
  expect_true(is.na(desc$zeros))
  finite <- dl_fit_data(lower = c(0, 1), upper = c(1, 2), frequency = c(1, 3))
  expect_equal(dl_fit_describe(finite)$mean, 1.25)
  expect_equal(dl_fit_describe(finite)$variance, var(c(.5, 1.5, 1.5, 1.5)))
  expect_error(dl_fit_data(lower = c(0, .5), upper = c(1, 2), frequency = c(1, 1)),
               "not overlap")
  expect_error(dl_fit_data(lower = 1, upper = 1, frequency = 1), "lower < upper")
  expect_error(dl_fit_data(1, lower = 0, upper = 1, frequency = 1), "without `x`")
  expect_error(dl_fit_data(lower = 0, frequency = 1), "require")
  # Empty infinite classes must not make finite-class descriptives unavailable.
  z <- dl_fit_data(lower = c(-Inf, 0), upper = c(0, 2), frequency = c(0, 2))
  expect_equal(dl_fit_describe(z)$mean, 1)
})

test_that("weighted descriptives agree with independently expanded small data", {
  x <- c(-1, 0, 3, 5)
  w <- c(2, 1, 4, 3)
  raw <- rep(x, w)
  desc <- dl_fit_describe(dl_fit_data(x, w))
  expect_equal(desc$mean, mean(raw))
  expect_equal(desc$variance, var(raw))
  expect_equal(desc$sd, sd(raw))
  expect_equal(unname(unlist(desc[c("q1", "median", "q3")])),
               unname(quantile(raw, c(.25, .5, .75))))
  expect_equal(desc$ties, length(raw) - length(x))
  expect_equal(desc$zeros, 1)
  expect_equal(desc$negatives, 2)
  expect_true(desc$integer)
  expect_true(is.na(dl_fit_describe(1)$variance))
  expect_true(is.na(dl_fit_describe(c(1, 1))$skewness))
  expect_equal(dl_fit_describe(dl_fit_data(c(0, 1), c(1e10, 1e10)))$median, .5)
})

test_that("pasted and uploaded tables preserve decimal commas and column selection", {
  csv <- fit_read_table(text = "value;frequency\n1,2;3\n2,4;5")
  expect_equal(csv$value, c(1.2, 2.4))
  expect_equal(csv$frequency, c(3, 5))
  tsv <- fit_read_table(text = "value\tcount\n1.2\t2\n2.5\t3")
  expect_equal(tsv$value, c(1.2, 2.5))
  one <- fit_read_table(text = "1,2\n2,3\n3,4")
  expect_equal(one[[1]], c(1.2, 2.3, 3.4))
  header <- fit_read_table(text = "valor\n1,2\n2,3")
  expect_equal(header$valor, c(1.2, 2.3))
  file <- tempfile(fileext = ".csv")
  writeLines("value;frequency\n1,2;3\n2,4;5", file)
  expect_equal(fit_read_table(path = file), csv)
  expect_error(fit_read_table(text = ""), "nonempty")
  expect_error(fit_read_table(text = "1", path = file), "exactly one")
  expect_error(fit_read_table(path = paste0(file, "missing")), "readable")
  expect_error(fit_read_table(text = "1", decimal_mark = NA_character_), "decimal_mark")
  expect_error(fit_read_table(text = "1", decimal_mark = c(".", ",")), "decimal_mark")
})

test_that("candidate eligibility checks support without restricting registry defaults", {
  c <- dl_fit_candidates(c(0, 1, 10))
  expect_equal(nrow(c), 21)
  expect_false(c$eligible[c$id == "bernoulli"])
  expect_true(c$eligible[c$id == "binomial"])
  expect_match(c$reason[c$id == "binomial"], "Fix")
  expect_false(c$eligible[c$id == "beta"])
  expect_true(c$eligible[c$id == "exponential"])
  expect_false(c$eligible[c$id == "gamma"])
  mixed <- dl_fit_candidates(c(-.5, 1.2))
  expect_false(any(mixed$eligible[mixed$type == "discrete"]))
  expect_true(mixed$eligible[mixed$id == "normal"])
  grouped <- dl_fit_data(lower = c(-1, 0), upper = c(0, 1), frequency = c(0, 2))
  choices <- dl_fit_candidates(grouped)
  expect_true(choices$eligible[choices$id == "beta"])
  expect_true(choices$eligible[choices$id == "bernoulli"])
  narrow <- dl_fit_data(lower = .1, upper = .9, frequency = 2)
  expect_false(any(dl_fit_candidates(narrow)$eligible[choices$type == "discrete"]))
})
